export const translations = { 'pt-BR': pt, en, es };

/** Interface strings are translated; unknown strings (including personal captions) pass through. */
export function translate(language: Language, key: string, variables: Variables = {}): string {
  const template = translations[language][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match);
}

export function useI18n() {
  const { preferences } = usePreferences();
  const locale = preferences.language;
  const t = useCallback((key: string, variables?: Variables) => translate(locale, key, variables), [locale]);
  return { t, locale };
}
